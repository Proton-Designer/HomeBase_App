/** Normalizes a Photon/OSM state value ("California" or "CA") to a 2-letter US code. */
export function toStateAbbr(raw: string | null | undefined): string {
  if (!raw) return '';
  const trimmed = raw.trim();
  if (/^[A-Za-z]{2}$/.test(trimmed)) return trimmed.toUpperCase();
  return NAME_TO_ABBR[trimmed.toLowerCase()] ?? '';
}
